def style_axis(ax: plt.Axes) -> None:
    ax.spines["top"].set_visible(False)
    ax.spines["right"].set_visible(False)
    ax.tick_params(labelsize=7)


def draw_panel(
    ax: plt.Axes,
    df: pd.DataFrame,
    x_col: str,
    y_col: str,
    title: str,
    min_n: int,
) -> Dict[str, object]:
    if x_col not in df.columns:
        ax.text(0.5, 0.5, "Domain unavailable", ha="center", va="center", transform=ax.transAxes, fontsize=8)
        ax.set_title(title, fontsize=8)
        ax.axis("off")
        return {"status": "missing_column", "x_col": x_col, "n": 0, "r": np.nan, "p": np.nan}

    tmp = pd.DataFrame({
        "x": safe_numeric(df[x_col]),
        "y": safe_numeric(df[y_col]),
    }).replace([np.inf, -np.inf], np.nan).dropna()

    if len(tmp) < min_n or tmp["x"].nunique() < 2 or tmp["y"].nunique() < 2:
        ax.text(
            0.5, 0.5,
            f"Insufficient data\nn={len(tmp)}",
            ha="center", va="center", transform=ax.transAxes, fontsize=8,
        )
        ax.set_title(title, fontsize=8)
        ax.axis("off")
        return {"status": "insufficient", "x_col": x_col, "n": len(tmp), "r": np.nan, "p": np.nan}

    r, p = stats.pearsonr(tmp["x"], tmp["y"])
    slope, intercept, _, _, _ = stats.linregress(tmp["x"], tmp["y"])

    ax.scatter(tmp["x"], tmp["y"], s=12, alpha=0.65, linewidths=0)
    xs = np.linspace(tmp["x"].min(), tmp["x"].max(), 100)
    ax.plot(xs, intercept + slope * xs, lw=1.2)
    ax.axhline(0, lw=0.6, ls="--", alpha=0.5)
    ax.axvline(0, lw=0.6, ls="--", alpha=0.5)

    p_txt = "p<0.001" if p < 0.001 else f"p={p:.3g}"
    ax.set_title(f"{title}\nn={len(tmp)}, r={r:.2f}, {p_txt}", fontsize=8)
    ax.set_xlabel(DOMAIN_LABELS.get(x_col, x_col), fontsize=7)
    ax.set_ylabel("cBAG", fontsize=7)
    ax.grid(True, alpha=0.18)
    style_axis(ax)

    return {
        "status": "plotted",
        "x_col": x_col,
        "n": len(tmp),
        "r": float(r),
        "p": float(p),
        "slope": float(slope),
        "intercept": float(intercept),
    }


def make_domain_figure(
    merged_by_cohort: Dict[str, pd.DataFrame],
    cbag_by_cohort: Dict[str, str],
    feature_set: str,
    domains: Sequence[str],
    domain_type: str,
    outdir: Path,
    formats: Sequence[str],
    min_n: int,
) -> List[Dict[str, object]]:
    n_rows = len(COHORTS)
    n_cols = len(domains)

    fig_w = 3.0 * n_cols
    fig_h = 2.5 * n_rows
    fig, axes = plt.subplots(n_rows, n_cols, figsize=(fig_w, fig_h), squeeze=False)

    stats_rows: List[Dict[str, object]] = []

    for i, cohort in enumerate(COHORTS):
        df = merged_by_cohort.get(cohort, pd.DataFrame())
        y_col = cbag_by_cohort.get(cohort, "")
        for j, domain in enumerate(domains):
            ax = axes[i, j]
            title = f"{cohort}: {DOMAIN_LABELS.get(domain, domain)}"
            if df.empty or not y_col:
                ax.text(0.5, 0.5, "No merged data", ha="center", va="center", transform=ax.transAxes, fontsize=8)
                ax.set_title(title, fontsize=8)
                ax.axis("off")
                row = {"status": "no_data", "x_col": domain, "n": 0, "r": np.nan, "p": np.nan}
            else:
                row = draw_panel(ax, df, domain, y_col, title, min_n=min_n)

            row.update({
                "feature_set": feature_set,
                "domain_type": domain_type,
                "cohort": cohort,
                "domain": domain,
                "cbag_col": y_col,
            })
            stats_rows.append(row)

    fig.suptitle(
        f"cBAG associations with harmonized cognitive domains ({feature_set}, {domain_type})",
        fontsize=13,
        y=0.995,
    )
    fig.tight_layout(rect=[0, 0, 1, 0.975])

    stem = f"Figure_CognitiveDomains_{feature_set}_{domain_type}"
    for fmt in formats:
        path = outdir / f"{stem}.{fmt}"
        fig.savefig(path, dpi=300, bbox_inches="tight")
        print(f"[INFO] Saved {path}")
    plt.close(fig)

    return stats_rows


# ---------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------
def main() -> None:
    args = parse_args()
    base_dir = Path(args.base_dir)
    results_root = Path(args.results_root) if args.results_root else base_dir / "results"
    composite_dir = Path(args.composite_dir) if args.composite_dir else results_root / "composite_cognition"
    outdir = Path(args.outdir) if args.outdir else composite_dir / "cbag_domain_associations"
    outdir.mkdir(parents=True, exist_ok=True)

    print("BASE_DIR:", base_dir)
    print("RESULTS_ROOT:", results_root)
    print("COMPOSITE_DIR:", composite_dir)
    print("OUTDIR:", outdir)
    print("FEATURE_SETS:", ", ".join(args.feature_sets))
    print("COHORTS:", ", ".join(args.cohorts))

    all_stats: List[Dict[str, object]] = []
    merge_reports: List[Dict[str, object]] = []

    for feature_set in args.feature_sets:
        print(f"\n[INFO] Processing feature set: {feature_set}")
        merged_by_cohort: Dict[str, pd.DataFrame] = {}
        cbag_by_cohort: Dict[str, str] = {}

        for cohort in args.cohorts:
            val_path = validation_csv_path(results_root, cohort, feature_set)
            comp_path = composite_csv_path(composite_dir, cohort)

            if not val_path.exists():
                print(f"[WARN] Missing validation CSV: {val_path}")
                merge_reports.append({
                    "feature_set": feature_set,
                    "cohort": cohort,
                    "issue": "missing_validation_csv",
                    "validation_path": str(val_path),
                    "composite_path": str(comp_path),
                })
                continue
            if not comp_path.exists():
                print(f"[WARN] Missing composite CSV: {comp_path}")
                merge_reports.append({
                    "feature_set": feature_set,
                    "cohort": cohort,
                    "issue": "missing_composite_csv",
                    "validation_path": str(val_path),
                    "composite_path": str(comp_path),
                })
                continue

            val = pd.read_csv(val_path, low_memory=False)
            comp = pd.read_csv(comp_path, low_memory=False)

            cbag_col = first_existing(val, CBAG_PRIORITY)
            if cbag_col is None:
                print(f"[WARN] No cBAG column found for {cohort} {feature_set}")
                merge_reports.append({
                    "feature_set": feature_set,
                    "cohort": cohort,
                    "issue": "missing_cbag_col",
                    "validation_path": str(val_path),
                    "composite_path": str(comp_path),
                })
                continue

            merged, report = choose_best_merge(val, comp, cohort)
            report.update({
                "feature_set": feature_set,
                "validation_path": str(val_path),
                "composite_path": str(comp_path),
                "cbag_col": cbag_col,
            })
            merge_reports.append(report)
            merged_by_cohort[cohort] = merged
            cbag_by_cohort[cohort] = cbag_col

            merged_path = outdir / f"cbag_cognitive_domain_merged_{feature_set}_{cohort}.csv"
            merged.to_csv(merged_path, index=False)

            domain_counts = {d: int(merged[d].notna().sum()) if d in merged.columns else 0 for d in DOMAINS_RAW + DOMAINS_RESID}
            print(
                f"[INFO] {cohort} {feature_set}: merge={report['merge_strategy']} "
                f"overlap={report['overlap']} cBAG={cbag_col} domain_nonmissing={domain_counts}"
            )

        all_stats.extend(
            make_domain_figure(
                merged_by_cohort=merged_by_cohort,
                cbag_by_cohort=cbag_by_cohort,
                feature_set=feature_set,
                domains=DOMAINS_RAW,
                domain_type="raw",
                outdir=outdir,
                formats=args.formats,
                min_n=args.min_n,
            )
        )

        all_stats.extend(
            make_domain_figure(
                merged_by_cohort=merged_by_cohort,
                cbag_by_cohort=cbag_by_cohort,
                feature_set=feature_set,
                domains=DOMAINS_RESID,
                domain_type="resid",
                outdir=outdir,
                formats=args.formats,
                min_n=args.min_n,
            )
        )

    stats_df = pd.DataFrame(all_stats)
    merge_df = pd.DataFrame(merge_reports)

    stats_path = outdir / "cbag_cognitive_domain_stats.csv"
    merge_path = outdir / "cbag_cognitive_domain_merge_report.csv"
    stats_df.to_csv(stats_path, index=False)
    merge_df.to_csv(merge_path, index=False)

    print("\n[DONE]")
    print("Stats:", stats_path)
    print("Merge report:", merge_path)
    print("Figures/output dir:", outdir)


if __name__ == "__main__":
    main()
