def safe_numeric(s: pd.Series) -> pd.Series:
    return pd.to_numeric(s, errors="coerce")


def first_existing(df: pd.DataFrame, candidates: Sequence[str]) -> Optional[str]:
    for c in candidates:
        if c in df.columns:
            return c
    lower_map = {str(c).lower(): c for c in df.columns}
    for c in candidates:
        if str(c).lower() in lower_map:
            return lower_map[str(c).lower()]
    return None


def norm_key(x) -> Optional[str]:
    """Normalize subject/session keys for cross-file merges."""
    if pd.isna(x):
        return None
    s = str(x).strip()
    if s == "" or s.lower() == "nan":
        return None

    s = re.sub(r"\.csv$", "", s)
    s = re.sub(r"_conn_plain$", "", s)
    s = re.sub(r"_master_T_?\d*$", "", s)
    s = re.sub(r"_temp_T_?\d*$", "", s)
    s = re.sub(r"^(R\d+)(y\d+)$", r"\1_\2", s)

    return s


def rid_from_any(x) -> Optional[str]:
    """Extract ADNI RID-like number from Rxxxx_y*, PTID, or plain numeric ID."""
    if pd.isna(x):
        return None
    s = str(x).strip()
    if s == "" or s.lower() == "nan":
        return None

    m = re.search(r"R(\d+)", s)
    if m:
        return str(int(m.group(1)))

    m = re.search(r"_S_(\d+)", s)
    if m:
        return str(int(m.group(1)))

    if re.fullmatch(r"\d+(\.0)?", s):
        return str(int(float(s)))

    return None


def adni_y_from_key(x) -> Optional[str]:
    if pd.isna(x):
        return None
    s = str(x)
    m = re.search(r"_y(\d+)", s, flags=re.IGNORECASE)
    if m:
        return f"y{m.group(1)}"
    return None


def possible_merge_keys(df: pd.DataFrame) -> List[str]:
    keys = []
    tokens = [
        "connectome", "subject", "participant", "match", "regional",
        "id", "rid", "ptid", "visit", "viscode", "runno", "med_id", "exam",
    ]
    for c in df.columns:
        low = str(c).lower()
        if any(t in low for t in tokens):
            keys.append(c)
    return keys


def choose_best_merge(
    val: pd.DataFrame,
    comp: pd.DataFrame,
    cohort: str,
) -> Tuple[pd.DataFrame, Dict[str, object]]:
    """Merge validation table with cognitive composites using best overlap.

    For ADNI, prefer RID+visit when possible. For other cohorts, exact normalized key is usually enough.
    """
    val = val.copy()
    comp = comp.copy()

    report = {
        "cohort": cohort,
        "merge_strategy": "none",
        "validation_key": "",
        "composite_key": "",
        "overlap": 0,
        "n_validation_rows": len(val),
        "n_composite_rows": len(comp),
        "merged_rows": 0,
    }

    val_keys = possible_merge_keys(val)
    comp_keys = possible_merge_keys(comp)

    # ------------------------------------------------------------------
    # ADNI special: validation keys often look like R4028_y4, whereas
    # metadata/composite may contain RID plus VISCODE/VISCODE2.
    # ------------------------------------------------------------------
    if cohort == "ADNI":
        val_key_candidates = [k for k in ["connectome_key", "subject_id", "connectome_full_key"] if k in val.columns]
        if not val_key_candidates:
            val_key_candidates = val_keys

        comp_rid_col = first_existing(comp, ["RID", "rid"])
        comp_visit_col = first_existing(comp, ["VISCODE", "VISCODE2", "visit", "Visit", "EXAMDATE"])

        if comp_rid_col is not None:
            for vk in val_key_candidates:
                val["_merge_rid"] = val[vk].map(rid_from_any)
                val["_merge_visit"] = val[vk].map(adni_y_from_key)
                comp["_merge_rid"] = comp[comp_rid_col].map(rid_from_any)

                if comp_visit_col is not None:
                    comp["_merge_visit"] = comp[comp_visit_col].astype(str).str.strip().str.lower()
                    # Normalize common ADNI visits: bl -> y0, m48 -> y4, m24 -> y2, etc.
                    visit_map = {
                        "bl": "y0", "baseline": "y0", "sc": "y0",
                        "m00": "y0", "m0": "y0", "0": "y0", "0.0": "y0",
                        "m12": "y1", "12": "y1", "12.0": "y1",
                        "m24": "y2", "24": "y2", "24.0": "y2",
                        "m36": "y3", "36": "y3", "36.0": "y3",
                        "m48": "y4", "48": "y4", "48.0": "y4",
                    }
                    comp["_merge_visit"] = comp["_merge_visit"].replace(visit_map)

                    overlap_pair = len(
                        set(zip(val["_merge_rid"], val["_merge_visit"])).intersection(
                            set(zip(comp["_merge_rid"], comp["_merge_visit"]))
                        )
                    )
                    if overlap_pair > 0:
                        comp_small = comp.sort_values(comp.columns.tolist()[0]).drop_duplicates(["_merge_rid", "_merge_visit"], keep="first")
                        merged = val.merge(comp_small, on=["_merge_rid", "_merge_visit"], how="left", suffixes=("", "_cog"))
                        report.update({
                            "merge_strategy": "ADNI_RID_visit",
                            "validation_key": vk,
                            "composite_key": f"{comp_rid_col}+{comp_visit_col}",
                            "overlap": overlap_pair,
                            "merged_rows": len(merged),
                        })
                        return merged, report

                # RID-only fallback
                overlap_rid = len(set(val["_merge_rid"].dropna()).intersection(set(comp["_merge_rid"].dropna())))
                if overlap_rid > report["overlap"]:
                    comp_small = comp.sort_index().drop_duplicates("_merge_rid", keep="first")
                    merged = val.merge(comp_small, on="_merge_rid", how="left", suffixes=("", "_cog"))
                    report.update({
                        "merge_strategy": "ADNI_RID_only",
                        "validation_key": vk,
                        "composite_key": comp_rid_col,
                        "overlap": overlap_rid,
                        "merged_rows": len(merged),
                    })
                    if overlap_rid > 0:
                        return merged, report

    # ------------------------------------------------------------------
    # General exact normalized key matching.
    # ------------------------------------------------------------------
    best = None
    for vk in val_keys:
        vnorm = val[vk].map(norm_key)
        vset = set(vnorm.dropna().astype(str))
        if not vset:
            continue
        for ck in comp_keys:
            cnorm = comp[ck].map(norm_key)
            cset = set(cnorm.dropna().astype(str))
            overlap = len(vset.intersection(cset))
            if best is None or overlap > best[0]:
                best = (overlap, vk, ck)

    if best is not None and best[0] > 0:
        overlap, vk, ck = best
        val["_merge_key"] = val[vk].map(norm_key)
        comp["_merge_key"] = comp[ck].map(norm_key)
        comp_small = comp.sort_index().drop_duplicates("_merge_key", keep="first")
        merged = val.merge(comp_small, on="_merge_key", how="left", suffixes=("", "_cog"))
        report.update({
            "merge_strategy": "normalized_exact",
            "validation_key": vk,
            "composite_key": ck,
            "overlap": overlap,
            "merged_rows": len(merged),
        })
        return merged, report

    # ------------------------------------------------------------------
    # Last resort: if row counts are identical, align by row order.
    # This should rarely be used; it is documented in the merge report.
    # ------------------------------------------------------------------
    if len(val) == len(comp):
        domain_cols = [c for c in comp.columns if c in DOMAINS_RAW + DOMAINS_RESID or c.endswith("_n_components") or c.endswith("_n_domains")]
        merged = val.copy()
        for c in domain_cols:
            merged[c] = comp[c].values
        report.update({
            "merge_strategy": "row_order_fallback",
            "validation_key": "row_index",
            "composite_key": "row_index",
            "overlap": len(val),
            "merged_rows": len(merged),
        })
        return merged, report

    merged = val.copy()
    report["merged_rows"] = len(merged)
    return merged, report


